#[derive(Default)]
struct Report {
    imported: usize,
    imported_links: usize,
    already_linked: Vec<String>,
    differs: Vec<(String, String)>,
    absent: Vec<String>,
    mismatched: Vec<(String, String)>,
    secrets: Vec<(String, Vec<(usize, &'static str)>)>,
    ignored: Vec<(String, String)>,
    review: Vec<(String, usize)>,
    notes: Vec<String>,
    modes: BTreeMap<String, u32>,
    absent_dirs: Vec<String>,
    da: Vec<String>,
    candidates: Vec<(String, Vec<String>, bool)>,
    link_dirs: Vec<String>,
    bootstrap: Vec<String>,
}

/// Start of a diff between the chezmoi source and the machine, capped.
fn short_diff(src_file: &Path, real: &Path) -> String {
    const MAX: usize = 40;
    let out = Command::new("diff")
        .args(["-u", "--label", "chezmoi", "--label", "machine"])
        .arg(src_file)
        .arg(real)
        .output();
    let Ok(out) = out else {
        return "(diff unavailable)".into();
    };
    let text = String::from_utf8_lossy(&out.stdout);
    if text.starts_with("Binary files") || text.is_empty() {
        return format!(
            "(binary files, sizes {} / {} bytes)",
            std::fs::metadata(src_file).map_or(0, |m| m.len()),
            std::fs::metadata(real).map_or(0, |m| m.len())
        );
    }
    let all: Vec<&str> = text.lines().collect();
    let mut s = all.iter().take(MAX).copied().collect::<Vec<_>>().join("\n");
    if all.len() > MAX {
        let _ = write!(s, "\n… ({} more line(s))", all.len() - MAX);
    }
    s
}

fn git_note(source: &Path, rel_src: &Path) -> Option<String> {
    let out = Command::new("git")
        .arg("-C")
        .arg(source)
        .args([
            "log",
            "--diff-filter=D",
            "--format=%h %ad %s",
            "--date=short",
            "-3",
            "--",
        ])
        .arg(rel_src)
        .output()
        .ok()?;
    let t = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!t.is_empty()).then_some(t)
}

fn count_files(dir: &Path) -> usize {
    let mut n = 0;
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            match e.file_type() {
                Ok(t) if t.is_dir() => n += count_files(&e.path()),
                Ok(_) => n += 1,
                Err(_) => {}
            }
        }
    }
    n
}

/// Real files and links (relative to `~`) under `dir`, except `__pycache__`.
fn real_files(home: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for e in rd.flatten() {
        if e.file_name() == "__pycache__" {
            continue;
        }
        let p = e.path();
        match e.file_type() {
            Ok(t) if t.is_dir() => real_files(home, &p, out),
            Ok(_) => out.push(p.strip_prefix(home).unwrap().to_string_lossy().into_owned()),
            Err(_) => {}
        }
    }
}

fn restricted(mode: u32) -> bool {
    mode & 0o077 == 0
}

pub fn run(env: &Env, repo: &Path, source: Option<&Path>, dry_run: bool) -> Result<()> {
    let source: PathBuf = match source {
        Some(s) => s.to_path_buf(),
        None => {
            let t = chezmoi(env, &env.data_home.join("chezmoi"), &["source-path"])
                .map(|s| s.trim().to_string())
                .unwrap_or_default();
            if t.is_empty() {
                env.data_home.join("chezmoi")
            } else {
                PathBuf::from(t)
            }
        }
    };
    if !source.is_dir() {
        bail!("chezmoi source not found: {}", source.display());
    }
    let config_root = repo.join("config");
    let ignore = Ignore::load(&config_root.join(META).join("ignore"))?;

    let files = lines(&chezmoi(
        env,
        &source,
        &["managed", "--include=files,symlinks"],
    )?);
    let dirs = lines(&chezmoi(env, &source, &["managed", "--include=dirs"])?);
    let file_src = source_paths(env, &source, &files)?;
    let dir_src = source_paths(env, &source, &dirs)?;
    let managed: BTreeSet<&str> = files.iter().map(String::as_str).collect();

    let mut r = Report::default();
    // Targets that could not be imported (to judge the cleanliness of a folder).
    let mut not_imported: BTreeSet<String> = BTreeSet::new();
    let mut to_write: Vec<(String, Vec<u8>, bool)> = Vec::new();
    let mut links_to_write: Vec<(String, PathBuf)> = Vec::new();

    for (target, srcp) in files.iter().zip(&file_src) {
        let rel_src = srcp.strip_prefix(&source).unwrap_or(srcp);
        let attrs = attrs_of(rel_src);
        let real = env.home.join(target);
        if let Some(rule) = ignore.matching(target) {
            r.ignored.push((target.clone(), rule.to_string()));
            not_imported.insert(target.clone());
            continue;
        }
        let md = match std::fs::symlink_metadata(&real) {
            Ok(m) => m,
            Err(_) => {
                r.absent.push(target.clone());
                not_imported.insert(target.clone());
                continue;
            }
        };
        // Already a link to config/ (rerun after a setup): we do not read our own repository again.
        if md.file_type().is_symlink() {
            if let Ok(t) = std::fs::canonicalize(&real) {
                if std::fs::canonicalize(&config_root).is_ok_and(|c| t.starts_with(c)) {
                    r.already_linked.push(target.clone());
                    continue;
                }
            }
        }
        if attrs.symlink {
            let want = std::fs::read_to_string(srcp).unwrap_or_default();
            let want = want.trim_end_matches('\n');
            if !md.file_type().is_symlink() {
                r.mismatched.push((
                    target.clone(),
                    "chezmoi expects a link, the machine has something else".into(),
                ));
                not_imported.insert(target.clone());
                continue;
            }
            let got = std::fs::read_link(&real)?;
            if got.to_string_lossy() != want {
                r.differs.push((
                    target.clone(),
                    format!("chezmoi target: {want}\nmachine target: {}", got.display()),
                ));
            }
            links_to_write.push((target.clone(), got));
            r.imported_links += 1;
            continue;
        }
        if md.file_type().is_symlink() || !md.is_file() {
            r.mismatched.push((
                target.clone(),
                "chezmoi expects an ordinary file, the machine has a link or a folder".into(),
            ));
            not_imported.insert(target.clone());
            continue;
        }
        let bytes = std::fs::read(&real).with_context(|| format!("reading {}", real.display()))?;
        let mut secret_found = false;
        if !is_binary(&bytes) {
            let sc = scan_secrets(&String::from_utf8_lossy(&bytes));
            if !sc.hits.is_empty() {
                r.secrets.push((target.clone(), sc.hits));
                not_imported.insert(target.clone());
                secret_found = true;
            } else if sc.mentions > 0 {
                r.review.push((target.clone(), sc.mentions));
            }
        }
        if secret_found {
            continue;
        }
        // Difference with the chezmoi source.
        let src_bytes = std::fs::read(srcp).unwrap_or_default();
        if src_bytes != bytes {
            r.differs.push((target.clone(), short_diff(srcp, &real)));
        }
        let mode = md.mode() & 0o777;
        let real_exec = mode & 0o111 != 0;
        if attrs.exec != real_exec {
            r.notes.push(format!(
                "{target}: chezmoi prefix {} but the real file {} executable (the real one is kept)",
                if attrs.exec { "executable_" } else { "without executable_" },
                if real_exec { "is" } else { "is not" }
            ));
        }
        if attrs.private != restricted(mode) {
            r.notes.push(if attrs.private {
                format!("{target}: prefix private_ but real permissions {mode:04o} (not restricted, nothing noted in modes)")
            } else {
                format!("{target}: real permissions {mode:04o} without prefix private_ (noted in modes)")
            });
        }
        if restricted(mode) {
            r.modes.insert(target.clone(), mode);
        }
        to_write.push((target.clone(), bytes, real_exec));
        r.imported += 1;
    }

    // Managed folders: restricted permissions, and absent folders (DA entries of chezmoi status).
    for (target, srcp) in dirs.iter().zip(&dir_src) {
        let rel_src = srcp.strip_prefix(&source).unwrap_or(srcp);
        let attrs = attrs_of(rel_src);
        let real = env.home.join(target);
        match std::fs::symlink_metadata(&real) {
            Ok(m) if m.is_dir() => {
                let mode = m.mode() & 0o777;
                if restricted(mode) {
                    r.modes.insert(target.clone(), mode);
                } else if attrs.private {
                    r.notes.push(format!(
                        "{target}/: prefix private_ but real permissions {mode:04o}"
                    ));
                }
            }
            Ok(_) => r
                .mismatched
                .push((format!("{target}/"), "chezmoi expects a folder".into())),
            Err(_) => {
                let has_managed = managed.iter().any(|f| f.starts_with(&format!("{target}/")));
                if !has_managed {
                    // Source folder without any managed file, absent from the machine.
                    let n = count_files(srcp);
                    let hist = git_note(&source, rel_src);
                    let mut d = format!(
                        "{target}/: folder absent from the machine; in the source, {} ({n} file(s)) ",
                        srcp.strip_prefix(&source).unwrap_or(srcp).display()
                    );
                    d.push_str(if n == 0 {
                        "is an EMPTY folder (leftover: its files were removed from the chezmoi repository, git does not keep empty folders)"
                    } else {
                        "still holds unmanaged files"
                    });
                    if let Some(h) = hist {
                        let _ = write!(d, ". Files removed by: {}", h.replace('\n', "; "));
                    }
                    r.da.push(d);
                } else {
                    r.absent_dirs.push(target.clone());
                }
            }
        }
    }

    // Cleanliness of the candidate folders for the folder link.
    let mut cand: BTreeSet<String> = CANDIDATE_DIRS.iter().map(|s| (*s).to_string()).collect();
    for p in CANDIDATE_PARENTS {
        if let Ok(rd) = std::fs::read_dir(env.home.join(p)) {
            for e in rd.flatten() {
                let rel = format!("{p}/{}", e.file_name().to_string_lossy());
                if e.path().is_dir() && managed.iter().any(|f| f.starts_with(&format!("{rel}/"))) {
                    cand.insert(rel);
                }
            }
        }
    }
    for c in PROPOSED_LINK_DIRS {
        cand.insert((*c).to_string());
    }
    for c in cand {
        let mut real = Vec::new();
        real_files(&env.home, &env.home.join(&c), &mut real);
        let unmanaged: Vec<String> = real
            .iter()
            .filter(|f| !managed.contains(f.as_str()))
            .cloned()
            .collect();
        let skipped = managed
            .iter()
            .any(|f| f.starts_with(&format!("{c}/")) && not_imported.contains(*f));
        let clean = unmanaged.is_empty() && !skipped;
        if clean && PROPOSED_LINK_DIRS.contains(&c.as_str()) {
            r.link_dirs.push(c.clone());
        }
        r.candidates.push((c, unmanaged, skipped));
    }

    // Files of the chezmoi repository that are not config: to bootstrap/.
    for name in ["README.md", "bootstrap.sh", "bootstrap-patches"] {
        if source.join(name).exists() {
            r.bootstrap.push(name.to_string());
        }
    }

    // ---- writes (poste repository only)
    if !dry_run {
        for (target, bytes, exec) in &to_write {
            let dst = config_root.join(target);
            if let Some(p) = dst.parent() {
                std::fs::create_dir_all(p)?;
            }
            if std::fs::symlink_metadata(&dst)
                .is_ok_and(|m| m.file_type().is_symlink() || m.is_dir())
            {
                bail!(
                    "{} exists in config/ with another type, giving up",
                    dst.display()
                );
            }
            let tmp = dst.with_file_name(format!(".poste-tmp-{}-import", std::process::id()));
            std::fs::write(&tmp, bytes)?;
            std::fs::set_permissions(
                &tmp,
                std::fs::Permissions::from_mode(if *exec { 0o755 } else { 0o644 }),
            )?;
            std::fs::rename(&tmp, &dst)?;
            if sha256_file(&dst)? != sha256_file(&env.home.join(target))? {
                bail!("copy of {target} differs from the original, giving up");
            }
        }
        for (target, link_to) in &links_to_write {
            let dst = config_root.join(target);
            if let Some(p) = dst.parent() {
                std::fs::create_dir_all(p)?;
            }
            if std::fs::symlink_metadata(&dst).is_ok_and(|m| m.file_type().is_symlink()) {
                std::fs::remove_file(&dst)?;
            }
            symlink(link_to, &dst).with_context(|| format!("link {}", dst.display()))?;
        }
        let meta = config_root.join(META);
        std::fs::create_dir_all(&meta)?;
        if !meta.join("ignore").exists() {
            std::fs::write(meta.join("ignore"), IGNORE_TEMPLATE)?;
        }
        // Restricted permissions of the imported files (modes file: add/replace).
        for (p, m) in &r.modes {
            config::upsert_mode_line(&config_root, p, *m)?;
        }
        if !r.link_dirs.is_empty() {
            let f = meta.join("link-dirs");
            let mut cur = std::fs::read_to_string(&f).unwrap_or_default();
            for d in &r.link_dirs {
                if !cur.lines().any(|l| l.trim() == d) {
                    if !cur.is_empty() && !cur.ends_with('\n') {
                        cur.push('\n');
                    }
                    cur.push_str(d);
                    cur.push('\n');
                }
            }
            std::fs::write(&f, cur)?;
        }
        if !r.bootstrap.is_empty() {
            let b = repo.join("bootstrap");
            std::fs::create_dir_all(&b)?;
            for name in &r.bootstrap {
                let from = source.join(name);
                if from.is_dir() {
                    copy_tree(&from, &b.join(name))?;
                } else {
                    std::fs::copy(&from, b.join(name))?;
                }
            }
        }
        ensure_gitignore(repo)?;
    }

    let text = render(&r, files.len(), dirs.len(), &source);
    if dry_run {
        println!("{text}");
        println!("\nDry run (--dry-run): nothing was written.");
    } else {
        let f = env.state_dir().join("import-chezmoi.md");
        std::fs::create_dir_all(env.state_dir())?;
        std::fs::write(&f, &text)?;
        println!(
            "Import done: {} file(s) and {} link(s) imported, {} refused for a secret, {} absent from the machine, {} different from the chezmoi source.\nReport: {}",
            r.imported,
            r.imported_links,
            r.secrets.len(),
            r.absent.len(),
            r.differs.len(),
            env.display(&f)
        );
    }
    Ok(())
}

/// `__pycache__` must never enter the repository (a folder linked as a block receives some).
fn ensure_gitignore(repo: &Path) -> Result<()> {
    let f = repo.join(".gitignore");
    let mut cur = std::fs::read_to_string(&f).unwrap_or_default();
    let mut changed = false;
    for l in ["__pycache__/", "*.pyc"] {
        if !cur.lines().any(|x| x.trim() == l) {
            if !cur.is_empty() && !cur.ends_with('\n') {
                cur.push('\n');
            }
            cur.push_str(l);
            cur.push('\n');
            changed = true;
        }
    }
    if changed {
        std::fs::write(&f, cur)?;
    }
    Ok(())
}

fn render(r: &Report, nfiles: usize, ndirs: usize, source: &Path) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Import from chezmoi\n");
    let _ = writeln!(
        s,
        "chezmoi source: `{}` ({nfiles} managed file(s) and link(s), {ndirs} folder(s)). The imported content is that of the machine (`~`), not that of the source.\n",
        source.display()
    );
    let _ = writeln!(s, "## Summary\n");
    let _ = writeln!(
        s,
        "- imported: {} file(s) and {} symbolic link(s) in `config/`",
        r.imported, r.imported_links
    );
    let _ = writeln!(
        s,
        "- different from the chezmoi source: {}",
        r.differs.len()
    );
    let _ = writeln!(
        s,
        "- managed but absent from the machine (not imported): {}",
        r.absent.len()
    );
    let _ = writeln!(s, "- refused for a secret: {}", r.secrets.len());
    let _ = writeln!(s, "- ignored by the exclusion rules: {}", r.ignored.len());
    let _ = writeln!(
        s,
        "- of a different type (not imported): {}",
        r.mismatched.len()
    );
    let _ = writeln!(
        s,
        "- already linked to `config/` (not read again): {}",
        r.already_linked.len()
    );
    let _ = writeln!(
        s,
        "- restricted permissions noted in `config/.poste/modes`: {}",
        r.modes.len()
    );
    let _ = writeln!(
        s,
        "- `DA` entries of `chezmoi status` explained: {}\n",
        r.da.len()
    );

    let _ = writeln!(
        s,
        "## Files where the machine differs from the chezmoi source\n"
    );
    if r.differs.is_empty() {
        let _ = writeln!(s, "None.\n");
    }
    for (t, d) in &r.differs {
        let _ = writeln!(s, "### `{t}`\n\n```diff\n{d}\n```\n");
    }

    let _ = writeln!(
        s,
        "## Managed by chezmoi but absent from the machine (not imported)\n"
    );
    if r.absent.is_empty() && r.absent_dirs.is_empty() {
        let _ = writeln!(s, "None.\n");
    }
    for t in &r.absent {
        let _ = writeln!(s, "- `{t}`");
    }
    for t in &r.absent_dirs {
        let _ = writeln!(s, "- folder `{t}/` (its files are listed above)");
    }
    let _ = writeln!(s);

    let _ = writeln!(s, "## `DA` entries of `chezmoi status`\n");
    if r.da.is_empty() {
        let _ = writeln!(s, "None.\n");
    } else {
        let _ = writeln!(s, "`D`: absent from the machine; `A`: `chezmoi apply` would create it. These are folders:\n");
        for d in &r.da {
            let _ = writeln!(s, "- {d}");
        }
        let _ = writeln!(
            s,
            "\nNo content is lost or to import: these folders no longer hold any file.\n"
        );
    }

    let _ = writeln!(s, "## Refused for a secret (values never copied)\n");
    if r.secrets.is_empty() {
        let _ = writeln!(s, "None.\n");
    }
    for (t, hits) in &r.secrets {
        let _ = writeln!(s, "- `{t}`: not imported");
        for (n, why) in hits.iter().take(10) {
            let _ = writeln!(s, "  - line {n}: {why}");
        }
        if hits.len() > 10 {
            let _ = writeln!(s, "  - … and {} more", hits.len() - 10);
        }
    }
    if !r.secrets.is_empty() {
        let _ = writeln!(s, "\nThese files stay in place in `~`, without a link or a copy. To decide: clean them (move the value to the keyring), or add them as they are if the detection is a false positive.");
    }
    let _ = writeln!(s);

    let _ = writeln!(
        s,
        "## Imported files that mention a sensitive keyword without an obvious value (to review)\n"
    );
    if r.review.is_empty() {
        let _ = writeln!(s, "None.\n");
    }
    for (t, n) in &r.review {
        let _ = writeln!(s, "- `{t}`: {n} line(s)");
    }
    let _ = writeln!(s);

    if !r.ignored.is_empty() {
        let _ = writeln!(s, "## Ignored by `config/.poste/ignore`\n");
        for (t, rule) in &r.ignored {
            let _ = writeln!(s, "- `{t}` (rule `{rule}`)");
        }
        let _ = writeln!(s);
    }
    if !r.mismatched.is_empty() {
        let _ = writeln!(
            s,
            "## Different type between chezmoi and the machine (not imported)\n"
        );
        for (t, w) in &r.mismatched {
            let _ = writeln!(s, "- `{t}`: {w}");
        }
        let _ = writeln!(s);
    }
    if !r.notes.is_empty() {
        let _ = writeln!(
            s,
            "## Permissions: differences between chezmoi prefixes and real files\n"
        );
        for n in &r.notes {
            let _ = writeln!(s, "- {n}");
        }
        let _ = writeln!(s);
    }
    if !r.modes.is_empty() {
        let _ = writeln!(
            s,
            "## Restricted permissions noted (`config/.poste/modes`)\n"
        );
        for (p, m) in &r.modes {
            let _ = writeln!(s, "- `{p}` {m:04o}");
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "## Candidate folders for the folder link\n");
    let _ = writeln!(
        s,
        "A real unmanaged file (except `__pycache__`) prevents the folder link.\n"
    );
    for (c, unmanaged, skipped) in &r.candidates {
        if unmanaged.is_empty() && !skipped {
            let _ = writeln!(
                s,
                "- `{c}`: clean{}",
                if r.link_dirs.contains(c) {
                    "; added to `config/.poste/link-dirs`"
                } else {
                    "; not proposed (to decide)"
                }
            );
        } else {
            let _ = writeln!(s, "- `{c}`: NOT clean, folder link impossible");
            if *skipped {
                let _ = writeln!(s, "  - a managed file could not be imported");
            }
            for u in unmanaged.iter().take(8) {
                let _ = writeln!(s, "  - real unmanaged file: `{u}`");
            }
            if unmanaged.len() > 8 {
                let _ = writeln!(s, "  - … and {} more", unmanaged.len() - 8);
            }
        }
    }
    let _ = writeln!(s);

    let _ = writeln!(s, "## Files of the chezmoi repository outside config\n");
    if r.bootstrap.is_empty() {
        let _ = writeln!(s, "None.");
    } else {
        let _ = writeln!(
            s,
            "Copied into `bootstrap/` of the poste repository: {}. These are installation scripts for apps (and their fixes): to integrate into `poste sys setup` later. They are not in `config/`.",
            r.bootstrap.iter().map(|b| format!("`{b}`")).collect::<Vec<_>>().join(", ")
        );
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    #[test]
    fn attributes_of_prefixes() {
        let a = attrs_of(Path::new("dot_config/private_foot/executable_dot_run"));
        assert!(a.exec && a.private && !a.symlink);
        let a = attrs_of(Path::new("dot_claude/skills/symlink_kris"));
        assert!(a.symlink && !a.exec);
        let a = attrs_of(Path::new("dot_bashrc"));
        assert!(!a.exec && !a.private);
    }

    #[test]
    fn obvious_secrets_detected() {
        let k = format!("-----BEGIN {} PRIVATE KEY-----", "RSA");
        assert!(!scan_secrets(&k).hits.is_empty());
        assert!(!scan_secrets("password=hunter22").hits.is_empty());
        assert!(!scan_secrets("\"api_key\": \"abcd1234efgh5678ijkl\"")
            .hits
            .is_empty());
        assert!(!scan_secrets("Authorization: Bearer abcdef1234567890abcd")
            .hits
            .is_empty());
        let gh = format!("x = ghp_{}", "a1".repeat(20));
        assert!(!scan_secrets(&gh).hits.is_empty());
    }

    #[test]
    fn common_false_positives_avoided() {
        for l in [
            "token = $TOKEN",
            "password = \"\"",
            "local token = getToken()",
            "// the token expires",
            "\"token_file\": \"/home/x/.config/token\"",
            "secret: {{ .secret }}",
            "bind = SUPER, T, exec, foo",
        ] {
            assert!(scan_secrets(l).hits.is_empty(), "{l}");
        }
        assert_eq!(scan_secrets("// the token expires").mentions, 1);
        assert!(scan_secrets("secret = base64.b64encode(x)").hits.is_empty());
        assert!(scan_secrets("passwordFor = n.ssid").hits.is_empty());
    }

    #[test]
    fn ignore_template_is_valid() {
        let rules = crate::ignore::parse(IGNORE_TEMPLATE);
        assert!(rules.contains(&".ssh/**".to_string()));
        assert!(crate::ignore::matches("**/.env.*", "a/.env.prod"));
    }

    fn chezmoi_present() -> bool {
        Command::new("chezmoi").arg("--version").output().is_ok()
    }

    /// Fake chezmoi source and temporary HOME: the real `~` is never read.
    #[test]
    fn full_import_in_a_temporary_home() {
        if !chezmoi_present() {
            return;
        }
        use std::fs;
        let d = tempfile::tempdir().unwrap();
        let (home, src, repo) = (
            d.path().join("home"),
            d.path().join("src"),
            d.path().join("repo"),
        );
        for p in [&home, &src, &repo] {
            fs::create_dir_all(p).unwrap();
        }
        let put = |root: &Path, rel: &str, c: &str| {
            let p = root.join(rel);
            fs::create_dir_all(p.parent().unwrap()).unwrap();
            fs::write(&p, c).unwrap();
            p
        };
        // Source chezmoi.
        put(&src, "dot_config/app/conf", "version=source\n");
        put(&src, "dot_config/app/executable_run", "#!/bin/sh\n");
        put(&src, "dot_config/private_priv/f", "x\n");
        put(&src, "dot_config/absent", "a\n");
        put(&src, "dot_config/leak", "no secret\n");
        put(&src, "dot_config/skills/symlink_x", "../target\n");
        put(&src, "README.md", "doc\n");
        put(&src, "bootstrap.sh", "#!/bin/sh\n");
        put(&src, ".chezmoiignore", "README.md\nbootstrap.sh\n");
        fs::create_dir_all(src.join("dot_config/empty.d")).unwrap();
        // Real state of the machine.
        put(&home, ".config/app/conf", "version=machine\n");
        let runf = put(&home, ".config/app/run", "#!/bin/sh\n");
        fs::set_permissions(&runf, fs::Permissions::from_mode(0o755)).unwrap();
        let f = put(&home, ".config/priv/f", "x\n");
        fs::set_permissions(&f, fs::Permissions::from_mode(0o600)).unwrap();
        fs::set_permissions(home.join(".config/priv"), fs::Permissions::from_mode(0o700)).unwrap();
        put(
            &home,
            ".config/leak",
            &format!("password={}\n", "hunter22xyz"),
        );
        symlink("../target", {
            fs::create_dir_all(home.join(".config/skills")).unwrap();
            home.join(".config/skills/x")
        })
        .unwrap();
        let env = Env::with_home(&home);
        let before = std::fs::read_to_string(home.join(".config/app/conf")).unwrap();

        run_import(&env, &repo, &src);

        let cfg = repo.join("config");
        assert_eq!(
            fs::read_to_string(cfg.join(".config/app/conf")).unwrap(),
            "version=machine\n"
        );
        assert_eq!(
            fs::metadata(cfg.join(".config/app/run")).unwrap().mode() & 0o111,
            0o111
        );
        assert_eq!(
            fs::read_link(cfg.join(".config/skills/x")).unwrap(),
            PathBuf::from("../target")
        );
        assert!(!cfg.join(".config/leak").exists(), "secret imported");
        assert!(!cfg.join(".config/absent").exists());
        let modes = fs::read_to_string(cfg.join(".poste/modes")).unwrap();
        assert!(modes.contains(".config/priv/f 0600") && modes.contains(".config/priv 0700"));
        assert!(cfg.join(".poste/ignore").is_file());
        assert!(
            repo.join("bootstrap/README.md").is_file()
                && repo.join("bootstrap/bootstrap.sh").is_file()
        );
        let report = fs::read_to_string(env.state_dir().join("import-chezmoi.md")).unwrap();
        assert!(report.contains("`.config/app/conf`") && report.contains("version=machine"));
        assert!(report.contains("`.config/absent`"));
        assert!(report.contains("`.config/leak`"));
        assert!(!report.contains("hunter22xyz"), "secret value copied");
        assert!(report.contains("empty.d"));
        // Nothing moved in HOME.
        assert_eq!(
            std::fs::read_to_string(home.join(".config/app/conf")).unwrap(),
            before
        );
        assert!(!home.join(".config/app/conf").is_symlink());

        // --dry-run on another repository: nothing written.
        let repo2 = d.path().join("repo2");
        fs::create_dir_all(&repo2).unwrap();
        run(&env, &repo2, Some(&src), true).unwrap();
        assert!(!repo2.join("config").exists() && !repo2.join("bootstrap").exists());
    }

    fn run_import(env: &Env, repo: &Path, src: &Path) {
        run(env, repo, Some(src), false).unwrap();
    }
}
