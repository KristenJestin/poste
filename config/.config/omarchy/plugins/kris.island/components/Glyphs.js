// Chemin de l'icône sous assets/ (« tabler/microphone »), ou "".
function iconFor(glyph) {
  var name = map[String(glyph || "")] || ""
  return name !== "" && tabler[name] ? "tabler/" + tabler[name] : ""
}

// Commandes média (lecture, pause, stop, précédent, suivant) : pleines par
// défaut, comme sur les lecteurs ; le contour seul y paraît trop maigre.
var solid = { "player-play": 1, "player-pause": 1, "player-stop": 1, "player-skip-back": 1,
              "player-skip-forward": 1, "player-track-prev": 1, "player-track-next": 1,
              "heart": 1, "heart-outline": 0 }
function prefersFilled(glyph) {
  var name = map[String(glyph || "")] || ""
  // Le nom intermédiaire prime (cœur plein 󰋑, cœur vide 󰋕 : même fichier Tabler).
  if (solid[name] !== undefined) return !!solid[name]
  return !!solid[tabler[name] || ""]
}
